// ─── Cluster layout ───────────────────────────────────────────────────────────
// Places `count` nodes on the tangent plane at `center`, spaced apart.
// Returns an array of position vectors slightly above the globe surface.
function layoutCluster(center, count, spacing = 0.018) {
  const normal  = center.clone().normalize();
  const tangent = new THREE.Vector3().crossVectors(new THREE.Vector3(0, 1, 0), normal).normalize();
  const bitangent = new THREE.Vector3().crossVectors(normal, tangent).normalize();

  const offsets = [];
  if (count === 1) {
    offsets.push([0, 0]);
  } else if (count === 2) {
    offsets.push([-0.5, 0], [0.5, 0]);
  } else if (count === 3) {
    // Equilateral triangle — all nodes same distance from center/hub
    const r3 = 0.35;
    offsets.push(
      [0, r3],                                           // top (hero)
      [-r3 * Math.sin(2 * Math.PI / 3), -r3 * 0.5],    // bottom-left
      [ r3 * Math.sin(2 * Math.PI / 3), -r3 * 0.5],    // bottom-right
    );
  } else if (count === 4) {
    offsets.push([-0.4, 0.4], [0.4, 0.4], [-0.4, -0.4], [0.4, -0.4]);
  }

  return offsets.map(([u, v]) => {
    return center.clone()
      .addScaledVector(tangent, u * spacing)
      .addScaledVector(bitangent, v * spacing)
      .normalize()
      .multiplyScalar(GLOBE_RADIUS + NODE_ALTITUDE);
  });
}

